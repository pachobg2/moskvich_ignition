#!/usr/bin/env python3
"""Regenerate web_ui.h from web/index.html (run after editing the UI).

    python tools/embed_ui.py

The page is gzip-compressed into a byte array; the ECU serves it with
`Content-Encoding: gzip` (every phone/PC browser handles that).
"""
import gzip
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "web" / "index.html").read_bytes().replace(b"\r\n", b"\n")
gz = gzip.compress(html, 9, mtime=0)          # mtime=0 -> reproducible output
rows = []
for i in range(0, len(gz), 16):
    rows.append("  " + ", ".join("0x%02x" % b for b in gz[i:i + 16]))
out = ("#pragma once\n// GENERATED by tools/embed_ui.py from web/index.html -- edit that file, not this one.\n"
       "static const unsigned int WEB_UI_GZ_LEN = %d;\n"
       "static const unsigned char WEB_UI_GZ[] PROGMEM = {\n%s\n};\n" % (len(gz), ",\n".join(rows)))
(root / "web_ui.h").write_text(out, encoding="utf-8", newline="\n")
print(f"web_ui.h: {len(html)} bytes of HTML -> {len(gz)} bytes gzipped")
