#!/usr/bin/env python3
"""Regenerate web_ui.h from web/index.html (run after editing the UI).

    python tools/embed_ui.py
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "web" / "index.html").read_text(encoding="utf-8")
assert ')UIRAW"' not in html
out = ('#pragma once\n// GENERATED by tools/embed_ui.py from web/index.html -- edit that file, not this one.\n'
       'static const char WEB_UI_HTML[] PROGMEM = R"UIRAW(' + html + ')UIRAW";\n')
(root / "web_ui.h").write_text(out, encoding="utf-8", newline="\n")
print(f"web_ui.h: {len(html)} bytes of HTML")
